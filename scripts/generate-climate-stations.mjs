// Builds the lookup of NOAA weather stations that publish 1991–2020 monthly
// climate normals: lib/geo/climateStations.ts
// Run: node scripts/generate-climate-stations.mjs
//
// Two public-domain NOAA sources, combined once at build time so the app never
// has to search for a station at request time:
//   - the normals file listing, which says which stations have normals
//   - the GHCN station list, which gives each one a name and coordinates
//
// Kept to WBAN/airport (USW) and COOP (USC) stations: those publish full
// temperature and precipitation normals, where many of the volunteer stations
// record precipitation only.
import { writeFileSync, mkdirSync } from "node:fs";

const ACCESS_INDEX = "https://www.ncei.noaa.gov/data/normals-monthly/1991-2020/access/";
const GHCN_STATIONS = "https://www.ncei.noaa.gov/pub/data/ghcn/daily/ghcnd-stations.txt";

const get = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} → ${res.status}`);
  return res.text();
};

console.log("Reading the normals station list…");
const index = await get(ACCESS_INDEX);
const withNormals = new Set(
  [...index.matchAll(/href="((?:USW|USC)[A-Z0-9]+)\.csv"/g)].map((m) => m[1]),
);
console.log(`  ${withNormals.size} stations publish monthly normals.`);

console.log("Reading station names and coordinates…");
const ghcn = await get(GHCN_STATIONS);

// Fixed-width: id 1-11, lat 13-20, lon 22-30, state 39-40, name 42-71.
const stations = [];
for (const line of ghcn.split("\n")) {
  const id = line.slice(0, 11).trim();
  if (!withNormals.has(id)) continue;
  const lat = Number(line.slice(12, 20));
  const lon = Number(line.slice(21, 30));
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const state = line.slice(38, 40).trim();
  const name = line.slice(41, 71).trim().replace(/\s+/g, " ");
  stations.push([id, Math.round(lat * 1000) / 1000, Math.round(lon * 1000) / 1000, name, state]);
}
stations.sort((a, b) => a[0].localeCompare(b[0]));

mkdirSync("lib/geo", { recursive: true });
const file = `// AUTO-GENERATED by scripts/generate-climate-stations.mjs — do not edit by hand.
// Source: NOAA NCEI 1991–2020 Climate Normals + GHCN station list (public domain).
// [id, latitude, longitude, name, state]
export type ClimateStation = [string, number, number, string, string];
export const CLIMATE_STATIONS: ClimateStation[] = ${JSON.stringify(stations)};
`;
writeFileSync("lib/geo/climateStations.ts", file);
console.log(`Wrote ${stations.length} stations, ${(file.length / 1024).toFixed(0)} KB.`);
