// Generates a static, pre-projected US map as SVG path data.
// Source: us-atlas (Census cartographic boundaries, public domain).
// Run: node scripts/generate-us-map.mjs
//
// Pre-rendering at build time keeps the homepage free of any runtime map
// library. Interactive choropleths (Phase 4) use d3-geo directly instead.
import { writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { geoAlbersUsa, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("us-atlas/states-10m.json");

const WIDTH = 975;
const HEIGHT = 610;

const states = feature(topo, topo.objects.states);
const nation = feature(topo, topo.objects.nation);
// Internal borders only — avoids double-drawing the coastline.
const borders = mesh(topo, topo.objects.states, (a, b) => a !== b);

const projection = geoAlbersUsa().fitSize([WIDTH, HEIGHT], nation);
const path = geoPath(projection);

// Round coordinates to one decimal. At background scale this is visually
// identical and cuts the payload by roughly two thirds.
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(n * 10) / 10));

const nationPath = round(path(nation));
const bordersPath = round(path(borders));

const statePaths = states.features
  .map((f) => ({ id: f.id, name: f.properties?.name ?? "", d: path(f) }))
  .filter((s) => s.d)
  .map((s) => ({ ...s, d: round(s.d) }));

mkdirSync("lib/geo", { recursive: true });
mkdirSync("public", { recursive: true });

// Backdrop: a static SVG served from /public and used as a CSS mask, so it
// is cached as an asset instead of inflating the page payload, while the
// page still controls its colour per theme. Alpha carries the two tones:
// a faint landmass fill under slightly stronger state borders.
const backdropSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}">
<path d="${nationPath}" fill="#fff" fill-opacity="0.34"/>
<path d="${bordersPath}" fill="none" stroke="#fff" stroke-opacity="0.85" stroke-width="0.9" stroke-linejoin="round"/>
</svg>
`;
writeFileSync("public/us-map.svg", backdropSvg);

// Per-state paths: only needed by interactive maps, kept in its own module
// so the homepage never pulls it into the bundle.
const statesFile = `// AUTO-GENERATED by scripts/generate-us-map.mjs — do not edit by hand.
// Source: us-atlas / US Census cartographic boundary files (public domain).
export type UsState = { id: string; name: string; d: string };
export const US_STATES: UsState[] = ${JSON.stringify(statePaths)};
`;
writeFileSync("lib/geo/usStates.ts", statesFile);

const kb = (s) => (s.length / 1024).toFixed(0);
console.log(`states: ${statePaths.length}`);
console.log(`backdrop -> public/us-map.svg      ${kb(backdropSvg)} KB`);
console.log(`states   -> lib/geo/usStates.ts    ${kb(statesFile)} KB`);
