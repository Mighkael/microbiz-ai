// Generates a lookup of county FIPS -> {name, state, lon, lat}.
// Source: us-atlas (Census cartographic boundaries, public domain).
// Used by the sourcing module to measure distance to supplier clusters.
// Run: node scripts/generate-county-centroids.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { geoCentroid } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("us-atlas/counties-10m.json");
const statesTopo = require("us-atlas/states-10m.json");

const counties = feature(topo, topo.objects.counties);
const states = feature(statesTopo, statesTopo.objects.states);

// State FIPS (first 2 digits of county id) -> state name.
const stateNames = new Map(states.features.map((f) => [String(f.id), f.properties?.name ?? ""]));

const out = {};
let skipped = 0;
for (const f of counties.features) {
  const id = String(f.id).padStart(5, "0");
  const [lon, lat] = geoCentroid(f);
  if (!Number.isFinite(lon) || !Number.isFinite(lat)) { skipped++; continue; }
  out[id] = {
    n: f.properties?.name ?? "",
    s: stateNames.get(id.slice(0, 2)) ?? "",
    // One decimal is ~11km — ample for ranking suppliers by distance.
    lon: Math.round(lon * 100) / 100,
    lat: Math.round(lat * 100) / 100,
  };
}

const body = `// AUTO-GENERATED by scripts/generate-county-centroids.mjs — do not edit.
// Source: us-atlas / US Census cartographic boundary files (public domain).
export type CountyCentroid = { n: string; s: string; lon: number; lat: number };
/** Keyed by 5-digit county FIPS (state + county). */
export const COUNTY_CENTROIDS: Record<string, CountyCentroid> = ${JSON.stringify(out)};
`;

mkdirSync("lib/geo", { recursive: true });
writeFileSync("lib/geo/countyCentroids.ts", body);
console.log(`counties: ${Object.keys(out).length}, skipped: ${skipped}, size: ${(body.length / 1024).toFixed(0)} KB`);
